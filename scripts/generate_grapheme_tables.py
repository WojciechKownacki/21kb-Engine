"""Reproduce the Unicode 17 extended grapheme tables from pinned local data."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "third_party/unicode"
OUTPUT = ROOT / "sources/engine/src/ui/UITextGraphemeData.inc"


def ranges(filename, field, predicate=lambda fields: True):
    result = []
    for line in (DATA / filename).read_text(encoding="utf-8").splitlines():
        fields = [part.strip() for part in line.split("#", 1)[0].split(";")]
        if len(fields) <= field or not predicate(fields):
            continue
        bounds = fields[0].split("..")
        result.append((int(bounds[0], 16), int(bounds[-1], 16), fields[field]))
    merged = []
    for first, last, value in sorted(result):
        if merged and first <= merged[-1][1]:
            raise ValueError(f"Overlapping ranges in {filename}")
        if merged and first == merged[-1][1] + 1 and value == merged[-1][2]:
            merged[-1] = (merged[-1][0], last, value)
        else:
            merged.append((first, last, value))
    return merged


def generate():
    manifest = json.loads((DATA / "sources.json").read_text(encoding="utf-8"))
    if manifest["version"] != "17.0.0":
        raise ValueError("Review the segmentation rules before updating Unicode")
    for name, source in manifest["files"].items():
        if hashlib.sha256((DATA / name).read_bytes()).hexdigest() != source["sha256"]:
            raise ValueError(f"Pinned source hash mismatch: {name}")
    lines = ["// Generated by scripts/generate_grapheme_tables.py; do not edit.",
             "// Unicode 17.0.0 data: see third_party/unicode/LICENSE (Unicode-3.0).", ""]
    for name, enum, values in [
        ("Grapheme", "Grapheme", ranges("GraphemeBreakProperty.txt", 1)),
        ("Indic", "Indic", ranges("DerivedCoreProperties.txt", 2, lambda f: f[1] == "InCB")),
        ("Pictographic", "", ranges("emoji-data.txt", 1, lambda f: f[1] == "Extended_Pictographic")),
    ]:
        lines.append(f"constexpr PropertyRange<{enum or 'bool'}> k{name}Ranges[] = {{")
        for first, last, value in values:
            prop = f"{enum}::{value}" if enum else "true"
            lines.append(f"    {{ 0x{first:04X}U, 0x{last:04X}U, {prop} }},")
        lines.extend(["};", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Grapheme tables are stale; run scripts/generate_grapheme_tables.py")
        print("Unicode source hashes and generated grapheme tables match")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
